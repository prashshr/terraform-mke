#!/usr/bin/env bash
#
# msr2-dummy-data.sh
#
# Populates a DTR-based Mirantis Secure Registry 2 (MSR2) instance with
# dummy data for testing/demonstration:
#   - USERS                 regular (non-admin) users
#   - COUNT_ORG             organizations (project equivalent)
#   - COUNT_TAGS_PER_REPO   tags pushed into one repository per org
#   - COUNT_PRIVATE_REPO    private repositories per org
#   - COUNT_PUBLIC_REPO     public repositories per org
#
# Connection + auth are READ from an environment file (default:
# artifacts/configs/msr2.env). Only the needed values are consumed:
#   MSR2_URL                e.g. https://msr2.samkhya.cloud
#   MSR2_ADMIN_USERNAME     admin account used to bootstrap data
#   MSR2_ADMIN_PASSWORD     admin password
#   MSR2_INSECURE           set to "true" to skip TLS verification (self-signed)
#
# Any of those may also be exported in the shell to override the env file.
# No Terraform code is modified by this script.
#
# Requires: bash, curl, jq, docker (for pushing dummy image tags).
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="${MSR2_ENV_FILE:-${ROOT_DIR}/artifacts/configs/msr2.env}"

# Track every local image we create so we can GC them afterwards.
PUSHED_LOCAL_REFS=()

cleanup_local_images() {
  if (( ${#PUSHED_LOCAL_REFS[@]} == 0 )); then
    return 0
  fi
  echo "Cleaning up ${#PUSHED_LOCAL_REFS[@]} local dummy image reference(s) from this node"
  for ref in "${PUSHED_LOCAL_REFS[@]}"; do
    docker rmi -f "${ref}" >/dev/null 2>&1 || true
  done
  docker image prune -f >/dev/null 2>&1 || true
  echo "Local image GC complete."
}

trap cleanup_local_images EXIT

# ---- tunable counts (override via environment) -----------------------------
USERS="${USERS:-5}"
COUNT_ORG="${COUNT_ORG:-5}"
COUNT_TAGS_PER_REPO="${COUNT_TAGS_PER_REPO:-10}"
COUNT_PRIVATE_REPO="${COUNT_PRIVATE_REPO:-2}"
COUNT_PUBLIC_REPO="${COUNT_PUBLIC_REPO:-4}"

# ---- connection defaults (overridable by env file, then by exported env) ---
if [[ -f "${ENV_FILE}" ]]; then
  set -a
  . "${ENV_FILE}"
  set +a
fi

MSR2_URL="${MSR2_URL:-https://msr2.samkhya.cloud}"
MSR2_ADMIN_USERNAME="${MSR2_ADMIN_USERNAME:-admin}"
MSR2_ADMIN_PASSWORD="${MSR2_ADMIN_PASSWORD:-mkepassword}"
MSR2_INSECURE="${MSR2_INSECURE:-true}"

if [[ ! -f "${ENV_FILE}" ]]; then
  mkdir -p "$(dirname "${ENV_FILE}")"
  cat > "${ENV_FILE}" <<EOF
# Auto-generated by msr2-dummy-data.sh. Edit values or export them to override.
MSR2_URL='${MSR2_URL}'
MSR2_ADMIN_USERNAME='${MSR2_ADMIN_USERNAME}'
MSR2_ADMIN_PASSWORD='${MSR2_ADMIN_PASSWORD}'
MSR2_INSECURE='${MSR2_INSECURE}'
EOF
  chmod 0600 "${ENV_FILE}"
  echo "Created starter env file: ${ENV_FILE}"
fi

# ---- varied base images for dummy repos ------------------------------------
BASE_IMAGES=(
  "alpine:latest"
  "alpine:3.15"
  "busybox:latest"
  "busybox:1.31"
  "nginx:latest"
  "nginx:1.20"
  "debian:latest"
  "debian:10"
  "ubuntu:latest"
  "ubuntu:20.04"
  "redis:latest"
  "redis:6.2"
  "node:18-alpine"
  "python:3.9-slim"
  "httpd:2.4"
)
BASE_IMAGE_INDEX=0

pick_base_image() {
  CURRENT_BASE_IMAGE="${BASE_IMAGES[BASE_IMAGE_INDEX]}"
  BASE_IMAGE_INDEX=$(( (BASE_IMAGE_INDEX + 1) % ${#BASE_IMAGES[@]} ))
}

MSR2_URL="${MSR2_URL%/}"

CURL_EXTRA=()
if [[ "${MSR2_INSECURE}" == "true" ]]; then
  CURL_EXTRA=(--insecure)
fi

API="${MSR2_URL}/api/v0"
echo "Target MSR2 API: ${API}"
echo "Plan: users=${USERS} orgs=${COUNT_ORG} tags/repo=${COUNT_TAGS_PER_REPO} private_repo/org=${COUNT_PRIVATE_REPO} public_repo/org=${COUNT_PUBLIC_REPO}"

# ---- helpers ----------------------------------------------------------------
api_get() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" "$@"
}
api_post() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    -H "Content-Type: application/json" "$@"
}
api_delete() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    -X DELETE -o /dev/null -w '%{http_code}' "$@"
}

login() {
  local http_code
  http_code="$(curl -sS "${CURL_EXTRA[@]}" -o /dev/null -w '%{http_code}' \
    -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    "${API}/repositories?count=1")"
  if [[ "${http_code}" != "200" ]]; then
    echo "ERROR: failed to authenticate to MSR2 (HTTP ${http_code})." >&2
    exit 1
  fi
  echo "Authenticated to MSR2 as ${MSR2_ADMIN_USERNAME}"
}

# Readable name pools
ORG_NAMES=("kai" "rune" "sita" "ren" "eira" "devi" "sora" "freya" "kavi" "odin" "meena" "zen" "tara" "sigrid" "yuki")
USER_NAMES=("arjun" "astrid" "ren" "priya" "bjorn" "kiran" "leif" "nita" "soren" "amit" "eira" "hari" "yuki" "raju" "lata")
REPO_NAMES=("lakshmi" "tor" "ganesh" "rune" "durga" "kai" "bharat" "freya" "indra" "sigyn" "omkar" "haru" "prasad" "ivar" "rohan")

# Check if SSO is enabled (accounts managed by MKE, not DTR)
SSO_ENABLED=false
if api_get "${API}/meta/settings" | jq -e '.sso == true' >/dev/null 2>&1; then
  SSO_ENABLED=true
fi

if [[ "${SSO_ENABLED}" == "true" ]]; then
  echo "NOTE: SSO is enabled — users/orgs are managed by MKE, not DTR."
  echo "      Skipping user/org creation; using 'admin' namespace for repos."
fi

org_exists() {
  local name="$1"
  # Orgs with SSO are MKE-managed; check if namespace exists via repositories
  local code
  code="$(api_get -o /dev/null -w '%{http_code}' "${API}/repositories?namespace=${name}&count=1")"
  [[ "${code}" == "200" ]]
}

create_org() {
  # With SSO, orgs cannot be created via DTR API — always fail gracefully
  echo "skip"
}

user_exists() {
  local username="$1"
  # With SSO, users are MKE-managed; always report as exists to skip creation
  [[ "${SSO_ENABLED}" == "true" ]]
}

create_user() {
  # With SSO, users cannot be created via DTR API — always fail gracefully
  echo "skip"
}

# Create a repo in a namespace via DTR API
repo_exists() {
  local org="$1" repo="$2"
  local http_code
  http_code="$(api_get -o /dev/null -w '%{http_code}' "${API}/repositories/${org}/${repo}")"
  [[ "${http_code}" == "200" ]]
}

create_repo() {
  local org="$1" repo="$2" visibility="$3"
  api_post -X POST "${API}/repositories/${org}" \
    -d "{\"name\":\"${repo}\",\"shortDescription\":\"dummy repo\",\"visibility\":\"${visibility}\"}" \
    -o /dev/null -w '%{http_code}'
}

push_dummy_image() {
  local org="$1" repo="$2" tag_count="$3" base_img="$4"
  local target="${MSR2_URL#*://}/${org}/${repo}"

  if ! docker login "${MSR2_URL#*://}" \
        --username "${MSR2_ADMIN_USERNAME}" \
        --password "${MSR2_ADMIN_PASSWORD}" >/dev/null 2>&1; then
    echo "  WARN: docker login to ${MSR2_URL#*://} failed; skipping image push for ${org}/${repo}" >&2
    return 0
  fi

  docker pull "${base_img}" >/dev/null 2>&1 || true

  local i tag ref
  for (( i=1; i<=tag_count; i++ )); do
    tag="v$(printf '%03d' "${i}")"
    ref="${target}:${tag}"
    docker tag "${base_img}" "${ref}" >/dev/null 2>&1
    PUSHED_LOCAL_REFS+=("${ref}")
    if docker push "${ref}" >/dev/null 2>&1; then
      echo "    docker push ${ref} (from ${base_img})"
    else
      echo "    WARN: failed to push ${ref}" >&2
    fi
  done
}

# ---- main ------------------------------------------------------------------
login

# 1) users (skipped when SSO is enabled)
if [[ "${SSO_ENABLED}" == "true" ]]; then
  echo
  echo "== Skipping ${USERS} dummy users (SSO enabled — managed by MKE) =="
else
  echo
  echo "== Creating ${USERS} dummy users =="
  for (( u=1; u<=USERS; u++ )); do
    uname="${USER_NAMES[$(( (u-1) % ${#USER_NAMES[@]} ))]}"
    upass="Passw0rd-$((RANDOM % 100000))"
    mail="${uname}@example.com"
    if user_exists "${uname}"; then
      echo "  exists: ${uname}"
    else
      code="$(create_user "${uname}" "${upass}" "${mail}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created: ${uname}"
      else
        echo "  WARN: create user ${uname} returned HTTP ${code}" >&2
      fi
    fi
  done
fi

# 2) orgs + repos + tags
echo
if [[ "${SSO_ENABLED}" == "true" ]]; then
  # Single pass into admin namespace (SSO prevents creating orgs via DTR)
  echo "== Creating repositories in 'admin' namespace (SSO enabled) =="
  ORG_LIST=("admin")
else
  echo "== Creating ${COUNT_ORG} organizations with repositories/tags =="
  ORG_LIST=()
  for (( o=1; o<=COUNT_ORG; o++ )); do
    ORG_LIST+=("${ORG_NAMES[$(( (o-1) % ${#ORG_NAMES[@]} ))]}")
  done
fi

for oname in "${ORG_LIST[@]}"; do
  if [[ "${SSO_ENABLED}" != "true" ]]; then
    if org_exists "${oname}"; then
      echo "  exists: ${oname}"
    else
      code="$(create_org "${oname}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created org: ${oname}"
      else
        echo "  WARN: create org ${oname} returned HTTP ${code}; skipping" >&2
        continue
      fi
    fi
  fi

  total_repo=$(( COUNT_PRIVATE_REPO + COUNT_PUBLIC_REPO ))
  for (( r=1; r<=total_repo; r++ )); do
    if (( r <= COUNT_PUBLIC_REPO )); then
      visibility="public"
    else
      visibility="private"
    fi
    rname="${REPO_NAMES[$(( (r-1) % ${#REPO_NAMES[@]} ))]}"
    pick_base_image
    if repo_exists "${oname}" "${rname}"; then
      echo "  exists: ${oname}/${rname}"
    else
      code="$(create_repo "${oname}" "${rname}" "${visibility}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created repo: ${oname}/${rname} (${visibility})"
      else
        echo "  WARN: create repo ${oname}/${rname} returned HTTP ${code}; skipping" >&2
        continue
      fi
    fi
    echo "  [${visibility}] ${oname}/${rname} (${COUNT_TAGS_PER_REPO} tags) image=${CURRENT_BASE_IMAGE}"
    push_dummy_image "${oname}" "${rname}" "${COUNT_TAGS_PER_REPO}" "${CURRENT_BASE_IMAGE}"
  done
done

echo
echo "Done. Summary:"
echo "  users created : ${USERS}"
echo "  orgs          : ${COUNT_ORG}"
echo "  repos/org     : ${COUNT_PRIVATE_REPO} private + ${COUNT_PUBLIC_REPO} public"
echo "  tags/repo     : ${COUNT_TAGS_PER_REPO}"
