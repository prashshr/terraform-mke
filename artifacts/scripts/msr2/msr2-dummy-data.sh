#!/usr/bin/env bash
#
# msr2-dummy-data.sh
#
# Populates a DTR-based Mirantis Secure Registry 2 (MSR2) instance with
# dummy data for testing/demonstration:
#   - USERS                 regular (non-admin) users
#   - COUNT_ORG             organizations (project equivalent)
#   - COUNT_TAGS_PER_REPO   tags pushed into one repository per org
#   - COUNT_PRIVATE_REPO    private repositories per org
#   - COUNT_PUBLIC_REPO     public repositories per org
#
# Connection + auth are READ from an environment file (default:
# artifacts/configs/msr2.env). Only the needed values are consumed:
#   MSR2_URL                e.g. https://msr2.samkhya.cloud
#   MSR2_ADMIN_USERNAME     admin account used to bootstrap data
#   MSR2_ADMIN_PASSWORD     admin password
#   MSR2_INSECURE           set to "true" to skip TLS verification (self-signed)
#   MKE_URL                 MKE3/UCP URL (for user/org creation via UCP API)
#   MKE_ADMIN_USERNAME      MKE3 admin username (default: admin)
#   MKE_ADMIN_PASSWORD      MKE3 admin password
#
# Any of those may also be exported in the shell to override the env file.
# No Terraform code is modified by this script.
#
# Requires: bash, curl, jq, docker (for pushing dummy image tags).
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="${MSR2_ENV_FILE:-${ROOT_DIR}/artifacts/configs/msr2.env}"

# Track every local image we create so we can GC them afterwards.
PUSHED_LOCAL_REFS=()

cleanup_local_images() {
  if (( ${#PUSHED_LOCAL_REFS[@]} == 0 )); then
    return 0
  fi
  echo "Cleaning up ${#PUSHED_LOCAL_REFS[@]} local dummy image reference(s) from this node"
  for ref in "${PUSHED_LOCAL_REFS[@]}"; do
    docker rmi -f "${ref}" >/dev/null 2>&1 || true
  done
  docker image prune -f >/dev/null 2>&1 || true
  echo "Local image GC complete."
}

trap cleanup_local_images EXIT

# ---- tunable counts (override via environment) -----------------------------
USERS="${USERS:-5}"
COUNT_ORG="${COUNT_ORG:-5}"
COUNT_TAGS_PER_REPO="${COUNT_TAGS_PER_REPO:-10}"
COUNT_PRIVATE_REPO="${COUNT_PRIVATE_REPO:-2}"
COUNT_PUBLIC_REPO="${COUNT_PUBLIC_REPO:-4}"

# ---- connection defaults (overridable by env file, then by exported env) ---
if [[ -f "${ENV_FILE}" ]]; then
  set -a
  . "${ENV_FILE}"
  set +a
fi

MSR2_URL="${MSR2_URL:-https://msr2.samkhya.cloud}"
MSR2_ADMIN_USERNAME="${MSR2_ADMIN_USERNAME:-admin}"
MSR2_ADMIN_PASSWORD="${MSR2_ADMIN_PASSWORD:-mkepassword}"
MSR2_INSECURE="${MSR2_INSECURE:-true}"

# Read MKE3 admin credentials from launchpad.yaml
LAUNCHPAD_FILE="${ROOT_DIR}/artifacts/configs/mke3/launchpad.yaml"
if [[ -f "${LAUNCHPAD_FILE}" ]]; then
  MKE_ADMIN_USERNAME="$(grep -E '^\s*adminUsername:' "${LAUNCHPAD_FILE}" | awk '{print $2}' | tr -d '"'"'" | head -1)"
  MKE_ADMIN_PASSWORD="$(grep -E '^\s*adminPassword:' "${LAUNCHPAD_FILE}" | awk '{print $2}' | tr -d '"'"'" | head -1)"
fi
MKE_ADMIN_USERNAME="${MKE_ADMIN_USERNAME:-admin}"
MKE_ADMIN_PASSWORD="${MKE_ADMIN_PASSWORD:-mkepassword}"

# MKE3/UCP URL — use the ELB external address (UCP auth is on port 443, not 6443)
# Can be overridden, or auto-detected from mkectl-upgrade.env
MKE_URL="${MKE_URL:-}"
if [[ -z "${MKE_URL}" ]]; then
  # Try to read from mkectl-upgrade.env
  UPGRADE_ENV="${ROOT_DIR}/artifacts/configs/mke4/mkectl-upgrade.env"
  if [[ -f "${UPGRADE_ENV}" ]]; then
    MKE_URL="$(grep -E '^MKCTL_MKE3_EXTERNAL_ADDRESS=' "${UPGRADE_ENV}" | cut -d= -f2- | tr -d "'\"")"
  fi
  # Fallback: extract from launchpad.yaml SANs
  if [[ -z "${MKE_URL}" && -f "${LAUNCHPAD_FILE}" ]]; then
    MKE_URL="$(grep -E '^\s*--san=.*elb\.' "${LAUNCHPAD_FILE}" | head -1 | sed 's/.*--san=//')"
  fi
  # Default
  MKE_URL="${MKE_URL:-mke3ui.samkhya.cloud}"
fi
# Strip protocol if present, add https://
MKE_URL="${MKE_URL#https://}"
MKE_URL="${MKE_URL#http://}"
MKE_URL="https://${MKE_URL}"

if [[ ! -f "${ENV_FILE}" ]]; then
  mkdir -p "$(dirname "${ENV_FILE}")"
  cat > "${ENV_FILE}" <<EOF
# Auto-generated by msr2-dummy-data.sh. Edit values or export them to override.
MSR2_URL='${MSR2_URL}'
MSR2_ADMIN_USERNAME='${MSR2_ADMIN_USERNAME}'
MSR2_ADMIN_PASSWORD='${MSR2_ADMIN_PASSWORD}'
MSR2_INSECURE='${MSR2_INSECURE}'
MKE_URL='${MKE_URL}'
MKE_ADMIN_USERNAME='${MKE_ADMIN_USERNAME}'
MKE_ADMIN_PASSWORD='${MKE_ADMIN_PASSWORD}'
EOF
  chmod 0600 "${ENV_FILE}"
  echo "Created starter env file: ${ENV_FILE}"
fi

# ---- varied base images for dummy repos ------------------------------------
BASE_IMAGES=(
  "alpine:latest"
  "alpine:3.15"
  "busybox:latest"
  "busybox:1.31"
  "nginx:latest"
  "nginx:1.20"
  "debian:latest"
  "debian:10"
  "ubuntu:latest"
  "ubuntu:20.04"
  "redis:latest"
  "redis:6.2"
  "node:18-alpine"
  "python:3.9-slim"
  "httpd:2.4"
)
BASE_IMAGE_INDEX=0

pick_base_image() {
  CURRENT_BASE_IMAGE="${BASE_IMAGES[BASE_IMAGE_INDEX]}"
  BASE_IMAGE_INDEX=$(( (BASE_IMAGE_INDEX + 1) % ${#BASE_IMAGES[@]} ))
}

MSR2_URL="${MSR2_URL%/}"

CURL_EXTRA=()
if [[ "${MSR2_INSECURE}" == "true" ]]; then
  CURL_EXTRA=(--insecure)
fi

API="${MSR2_URL}/api/v0"
MKE_API="${MKE_URL}"
echo "Target MSR2 API: ${API}"
echo "Target MKE3 API: ${MKE_API}"
echo "Plan: users=${USERS} orgs=${COUNT_ORG} tags/repo=${COUNT_TAGS_PER_REPO} private_repo/org=${COUNT_PRIVATE_REPO} public_repo/org=${COUNT_PUBLIC_REPO}"

# ---- MKE3/UCP API helpers (bearer token auth) -------------------------------
MKE_TOKEN=""

mke_login() {
  local resp
  resp="$(curl -sS "${CURL_EXTRA[@]}" -kL \
    -H 'accept: application/json' -H 'content-type: application/json' \
    -d "{\"username\":\"${MKE_ADMIN_USERNAME}\",\"password\":\"${MKE_ADMIN_PASSWORD}\"}" \
    "${MKE_API}/auth/login")"
  MKE_TOKEN="$(echo "${resp}" | jq -r '.auth_token // empty')"
  if [[ -z "${MKE_TOKEN}" ]]; then
    echo "ERROR: failed to authenticate to MKE3 at ${MKE_API}." >&2
    echo "  Response: ${resp}" >&2
    return 1
  fi
  echo "Authenticated to MKE3 as ${MKE_ADMIN_USERNAME}"
}

mke_api_get() {
  curl -sS "${CURL_EXTRA[@]}" -kL \
    -H 'accept: application/json' \
    -H "Authorization: Bearer ${MKE_TOKEN}" \
    "$@"
}

mke_api_post() {
  curl -sS "${CURL_EXTRA[@]}" -kL \
    -H 'accept: application/json' -H 'content-type: application/json' \
    -H "Authorization: Bearer ${MKE_TOKEN}" \
    "$@"
}

mke_api_put() {
  curl -sS "${CURL_EXTRA[@]}" -kL \
    -X PUT \
    -H 'accept: application/json' -H 'content-type: application/json' \
    -H "Authorization: Bearer ${MKE_TOKEN}" \
    "$@"
}

# Create a user via MKE3 UCP API
mke_user_exists() {
  local name="$1"
  local http_code
  http_code="$(mke_api_get -o /dev/null -w '%{http_code}' "${MKE_API}/accounts/${name}")"
  [[ "${http_code}" == "200" ]]
}

mke_create_user() {
  local name="$1" password="$2"
  mke_api_post -X POST "${MKE_API}/accounts/" \
    -d "{\"fullName\":\"${name}\",\"isActive\":true,\"isAdmin\":false,\"isOrg\":false,\"password\":\"${password}\",\"name\":\"${name}\"}" \
    -o /dev/null -w '%{http_code}'
}

# Create an org via MKE3 UCP API
mke_org_exists() {
  local name="$1"
  local http_code
  http_code="$(mke_api_get -o /dev/null -w '%{http_code}' "${MKE_API}/accounts/${name}")"
  [[ "${http_code}" == "200" ]]
}

mke_create_org() {
  local name="$1"
  mke_api_post -X POST "${MKE_API}/accounts/" \
    -d "{\"name\":\"${name}\",\"isOrg\":true}" \
    -o /dev/null -w '%{http_code}'
}

mke_get_org_id() {
  local name="$1"
  mke_api_get "${MKE_API}/accounts/${name}" | jq -r '.id // empty'
}

# ---- DTR API helpers (basic auth for repos/images) --------------------------

# ---- helpers ----------------------------------------------------------------
api_get() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" "$@"
}
api_post() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    -H "Content-Type: application/json" "$@"
}
api_delete() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    -X DELETE -o /dev/null -w '%{http_code}' "$@"
}

login() {
  local http_code
  http_code="$(curl -sS "${CURL_EXTRA[@]}" -o /dev/null -w '%{http_code}' \
    -u "${MSR2_ADMIN_USERNAME}:${MSR2_ADMIN_PASSWORD}" \
    "${API}/repositories?count=1")"
  if [[ "${http_code}" != "200" ]]; then
    echo "ERROR: failed to authenticate to MSR2 (HTTP ${http_code})." >&2
    exit 1
  fi
  echo "Authenticated to MSR2 as ${MSR2_ADMIN_USERNAME}"
}

# Readable name pools (for orgs/users — repos use base image names)
ORG_NAMES=("kai" "rune" "sita" "ren" "eira" "devi" "sora" "freya" "kavi" "odin" "meena" "zen" "tara" "sigrid" "yuki")
USER_NAMES=("arjun" "astrid" "ren" "priya" "bjorn" "kiran" "leif" "nita" "soren" "amit" "eira" "hari" "yuki" "raju" "lata")

# Generate tags derived from the base image tag.
# First tag preserves the original (e.g. "latest", "1.20"); subsequent tags
# increment as plausible versions when the tag looks numeric, else append index.
generate_tags() {
  local base_tag="$1" count="$2"
  local i
  printf '%s\n' "${base_tag}"
  if [[ "${base_tag}" =~ ^([0-9]+)\.([0-9]+)$ ]]; then
    # X.Y → X.Y.1, X.Y.2, ...
    local major="${BASH_REMATCH[1]}" minor="${BASH_REMATCH[2]}"
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${major}.${minor}.${i}"
    done
  elif [[ "${base_tag}" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
    # X.Y.Z → increment patch
    local major="${BASH_REMATCH[1]}" minor="${BASH_REMATCH[2]}" patch="${BASH_REMATCH[3]}"
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${major}.${minor}.$((patch + i))"
    done
  else
    # latest, slim, alpine, etc → append index
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${base_tag}-${i}"
    done
  fi
}

# Check if SSO is enabled (accounts managed by MKE, not DTR)
SSO_ENABLED=false
if api_get "${API}/meta/settings" | jq -e '.sso == true' >/dev/null 2>&1; then
  SSO_ENABLED=true
fi

if [[ "${SSO_ENABLED}" == "true" ]]; then
  echo "NOTE: SSO is enabled — users/orgs are managed by MKE3 (UCP API)."
fi

# Create a repo in a namespace via DTR API
repo_exists() {
  local org="$1" repo="$2"
  local http_code
  http_code="$(api_get -o /dev/null -w '%{http_code}' "${API}/repositories/${org}/${repo}")"
  [[ "${http_code}" == "200" ]]
}

create_repo() {
  local org="$1" repo="$2" visibility="$3"
  api_post -X POST "${API}/repositories/${org}" \
    -d "{\"name\":\"${repo}\",\"shortDescription\":\"dummy repo\",\"visibility\":\"${visibility}\"}" \
    -o /dev/null -w '%{http_code}'
}

push_dummy_image() {
  local org="$1" repo="$2" tag_count="$3" base_img="$4"
  local target="${MSR2_URL#*://}/${org}/${repo}"
  local base_tag="${base_img##*:}"

  if ! docker login "${MSR2_URL#*://}" \
        --username "${MSR2_ADMIN_USERNAME}" \
        --password "${MSR2_ADMIN_PASSWORD}" >/dev/null 2>&1; then
    echo "  WARN: docker login to ${MSR2_URL#*://} failed; skipping image push for ${org}/${repo}" >&2
    return 0
  fi

  docker pull "${base_img}" >/dev/null 2>&1 || true

  local tag ref
  while IFS= read -r tag; do
    ref="${target}:${tag}"
    docker tag "${base_img}" "${ref}" >/dev/null 2>&1
    PUSHED_LOCAL_REFS+=("${ref}")
    if docker push "${ref}" >/dev/null 2>&1; then
      echo "    docker push ${ref} (from ${base_img})"
    else
      echo "    WARN: failed to push ${ref}" >&2
    fi
  done < <(generate_tags "${base_tag}" "${tag_count}")
}

# ---- main ------------------------------------------------------------------
login

# Authenticate to MKE3 if SSO is enabled (needed for user/org creation)
if [[ "${SSO_ENABLED}" == "true" ]]; then
  mke_login
fi

# 1) users — created via MKE3 UCP API when SSO is enabled
echo
USER_LIST=()
if [[ "${SSO_ENABLED}" == "true" ]]; then
  echo "== Creating ${USERS} dummy users via MKE3 UCP API =="
  for (( u=1; u<=USERS; u++ )); do
    uname="${USER_NAMES[$(( (u-1) % ${#USER_NAMES[@]} ))]}"
    upass="Passw0rd-$((RANDOM % 100000))"
    USER_LIST+=("${uname}")
    if mke_user_exists "${uname}"; then
      echo "  exists: ${uname}"
    else
      code="$(mke_create_user "${uname}" "${upass}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created: ${uname}"
      else
        echo "  WARN: create user ${uname} returned HTTP ${code}" >&2
      fi
    fi
  done
else
  echo "== Skipping users (SSO disabled — DTR manages its own users) =="
fi

# 2) orgs — created via MKE3 UCP API when SSO is enabled
echo
ORG_LIST=()
if [[ "${SSO_ENABLED}" == "true" ]]; then
  echo "== Creating ${COUNT_ORG} organizations via MKE3 UCP API =="
else
  echo "== Creating ${COUNT_ORG} organizations via DTR API =="
fi

for (( o=1; o<=COUNT_ORG; o++ )); do
  oname="${ORG_NAMES[$(( (o-1) % ${#ORG_NAMES[@]} ))]}"
  ORG_LIST+=("${oname}")

  if [[ "${SSO_ENABLED}" == "true" ]]; then
    if mke_org_exists "${oname}"; then
      echo "  exists: ${oname}"
    else
      code="$(mke_create_org "${oname}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created org: ${oname}"
      else
        echo "  WARN: create org ${oname} returned HTTP ${code}; skipping" >&2
        unset 'ORG_LIST[-1]'
        continue
      fi
    fi
  fi
done

# 3) push images to USER personal namespaces (like msr4)
echo
echo "== Pushing images to user namespaces =="
for uname in "${USER_LIST[@]}"; do
  # Each user gets private repos
  total_user_repo="${COUNT_PRIVATE_REPO}"
  for (( r=1; r<=total_user_repo; r++ )); do
    pick_base_image
    rname="${CURRENT_BASE_IMAGE%%:*}"
    if repo_exists "${uname}" "${rname}"; then
      echo "  exists: ${uname}/${rname}"
    else
      code="$(create_repo "${uname}" "${rname}" "private")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created repo: ${uname}/${rname} (private)"
      else
        echo "  WARN: create repo ${uname}/${rname} returned HTTP ${code}; skipping" >&2
        continue
      fi
    fi
    echo "  [private] ${uname}/${rname} (${COUNT_TAGS_PER_REPO} tags) image=${CURRENT_BASE_IMAGE}"
    push_dummy_image "${uname}" "${rname}" "${COUNT_TAGS_PER_REPO}" "${CURRENT_BASE_IMAGE}"
  done
done

# 4) push images to ORG namespaces
echo
echo "== Pushing images to org namespaces =="
for oname in "${ORG_LIST[@]}"; do
  total_repo=$(( COUNT_PRIVATE_REPO + COUNT_PUBLIC_REPO ))
  for (( r=1; r<=total_repo; r++ )); do
    if (( r <= COUNT_PUBLIC_REPO )); then
      visibility="public"
    else
      visibility="private"
    fi
    pick_base_image
    # Repo name = base image name (e.g. nginx, alpine, busybox)
    rname="${CURRENT_BASE_IMAGE%%:*}"
    if repo_exists "${oname}" "${rname}"; then
      echo "  exists: ${oname}/${rname}"
    else
      code="$(create_repo "${oname}" "${rname}" "${visibility}")"
      if [[ "${code}" == "201" || "${code}" == "200" ]]; then
        echo "  created repo: ${oname}/${rname} (${visibility})"
      else
        echo "  WARN: create repo ${oname}/${rname} returned HTTP ${code}; skipping" >&2
        continue
      fi
    fi
    echo "  [${visibility}] ${oname}/${rname} (${COUNT_TAGS_PER_REPO} tags) image=${CURRENT_BASE_IMAGE}"
    push_dummy_image "${oname}" "${rname}" "${COUNT_TAGS_PER_REPO}" "${CURRENT_BASE_IMAGE}"
  done
done

echo
echo "Done. Summary:"
echo "  users created : ${#USER_LIST[@]}"
echo "  orgs          : ${#ORG_LIST[@]}"
echo "  repos/user    : ${COUNT_PRIVATE_REPO} private"
echo "  repos/org     : ${COUNT_PRIVATE_REPO} private + ${COUNT_PUBLIC_REPO} public"
echo "  tags/repo     : ${COUNT_TAGS_PER_REPO}"
