#!/usr/bin/env bash
#
# msr4-dummy-data.sh
#
# Populates a Harbor-based Mirantis Secure Registry 4 (MSR4) instance with
# dummy data for testing/demonstration:
#   - USERS                 regular (non-admin) users
#   - COUNT_PROJECT         projects
#   - COUNT_TAGS_PER_PROJECT tags pushed into one repository per project
#   - COUNT_PRIVATE_REPO    private repositories per project
#   - COUNT_PUBLIC_REPO     public repositories per project
#
# Connection + auth are READ from an environment file (default:
# artifacts/configs/msr4.env). Only the needed values are consumed:
#   MSR4_URL                e.g. https://msr.samkhya.cloud:443  (or :33002)
#   MSR4_ADMIN_USERNAME     admin account used to bootstrap data
#   MSR4_ADMIN_PASSWORD     admin password
#   MSR4_INSECURE           set to "true" to skip TLS verification (self-signed)
#
# Any of those may also be exported in the shell to override the env file.
# No Terraform code is modified by this script.
#
# Requires: bash, curl, jq, docker (for pushing dummy image tags).
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="${MSR4_ENV_FILE:-${ROOT_DIR}/artifacts/configs/msr4.env}"

# Track every local image we create so we can GC them afterwards.
PUSHED_LOCAL_REFS=()

# Remove the local dummy images we tagged/pushed, then run docker image GC
# so the build node does not accumulate the dummy layers.
cleanup_local_images() {
  if (( ${#PUSHED_LOCAL_REFS[@]} == 0 )); then
    return 0
  fi
  echo "Cleaning up ${#PUSHED_LOCAL_REFS[@]} local dummy image reference(s) from this node"
  for ref in "${PUSHED_LOCAL_REFS[@]}"; do
    docker rmi -f "${ref}" >/dev/null 2>&1 || true
  done
  # prune dangling (untagged) images left behind by the removed tags
  docker image prune -f >/dev/null 2>&1 || true
  echo "Local image GC complete."
}

# always remove local dummy images when the script ends
trap cleanup_local_images EXIT

# ---- tunable counts (override via environment) -----------------------------
USERS="${USERS:-5}"
COUNT_PROJECT="${COUNT_PROJECT:-5}"
COUNT_TAGS_PER_PROJECT="${COUNT_TAGS_PER_PROJECT:-10}"
COUNT_PRIVATE_REPO="${COUNT_PRIVATE_REPO:-2}"
COUNT_PUBLIC_REPO="${COUNT_PUBLIC_REPO:-4}"

# ---- connection defaults (overridable by env file, then by exported env) ---
# Precedence: exported env var  >  env file  >  built-in default.
if [[ -f "${ENV_FILE}" ]]; then
  # only pull in the keys we care about; ignore the rest
  set -a
  . "${ENV_FILE}"
  set +a
fi

# Apply built-in defaults, then let exported env vars supersede the file.
MSR4_URL="${MSR4_URL:-https://msr4.samkhya.cloud:443}"
MSR4_ADMIN_USERNAME="${MSR4_ADMIN_USERNAME:-admin}"
MSR4_ADMIN_PASSWORD="${MSR4_ADMIN_PASSWORD:-Harbor12345}"
MSR4_INSECURE="${MSR4_INSECURE:-true}"

# If the env file is missing, create a starter one with the resolved values so
# the next run is reproducible. This never blocks execution.
if [[ ! -f "${ENV_FILE}" ]]; then
  mkdir -p "$(dirname "${ENV_FILE}")"
  cat > "${ENV_FILE}" <<EOF
# Auto-generated by msr4-dummy-data.sh. Edit values or export them to override.
MSR4_URL='${MSR4_URL}'
MSR4_ADMIN_USERNAME='${MSR4_ADMIN_USERNAME}'
MSR4_ADMIN_PASSWORD='${MSR4_ADMIN_PASSWORD}'
MSR4_INSECURE='${MSR4_INSECURE}'
EOF
  chmod 0600 "${ENV_FILE}"
  echo "Created starter env file: ${ENV_FILE}"
fi

# ---- varied base images for dummy repos (mix of latest + old versions) -----
# Used to exercise MSR4 scanning across different distros/layers. Override the
# whole set by exporting BASE_IMAGES (space-separated "name:tag" entries).
BASE_IMAGES=(
  "alpine:latest"
  "alpine:3.15"
  "busybox:latest"
  "busybox:1.31"
  "nginx:latest"
  "nginx:1.20"
  "debian:latest"
  "debian:10"
  "ubuntu:latest"
  "ubuntu:20.04"
  "redis:latest"
  "redis:6.2"
  "node:18-alpine"
  "python:3.9-slim"
  "httpd:2.4"
)
BASE_IMAGE_INDEX=0

# Round-robin through BASE_IMAGES so each repo gets a different image.
# Sets the global CURRENT_BASE_IMAGE (no subshell, so the index persists).
pick_base_image() {
  CURRENT_BASE_IMAGE="${BASE_IMAGES[BASE_IMAGE_INDEX]}"
  BASE_IMAGE_INDEX=$(( (BASE_IMAGE_INDEX + 1) % ${#BASE_IMAGES[@]} ))
}

# strip any trailing slash for clean URL joining
MSR4_URL="${MSR4_URL%/}"

CURL_EXTRA=()
if [[ "${MSR4_INSECURE}" == "true" ]]; then
  CURL_EXTRA=(--insecure)
fi

API="${MSR4_URL}/api/v2.0"
echo "Target MSR4 API: ${API}"
echo "Plan: users=${USERS} projects=${COUNT_PROJECT} tags/project=${COUNT_TAGS_PER_PROJECT} private_repo/project=${COUNT_PRIVATE_REPO} public_repo/project=${COUNT_PUBLIC_REPO}"

# ---- helpers ----------------------------------------------------------------
api_get() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR4_ADMIN_USERNAME}:${MSR4_ADMIN_PASSWORD}" "$@"
}
api_post() {
  curl -sS "${CURL_EXTRA[@]}" -u "${MSR4_ADMIN_USERNAME}:${MSR4_ADMIN_PASSWORD}" \
    -H "Content-Type: application/json" "$@"
}

login() {
  local http_code
  http_code="$(api_get -o /dev/null -w '%{http_code}' "${API}/users/current")"
  if [[ "${http_code}" != "200" ]]; then
    echo "ERROR: failed to authenticate to MSR4 (HTTP ${http_code})." >&2
    exit 1
  fi
  echo "Authenticated to MSR4 as ${MSR4_ADMIN_USERNAME}"
}

# Readable name pools (cycle through by index — repos use base image names)
PROJECT_NAMES=("kai" "rune" "sita" "ren" "eira" "devi" "sora" "freya" "kavi" "odin" "meena" "zen" "tara" "sigrid" "yuki")
USER_NAMES=("arjun" "astrid" "ren" "priya" "bjorn" "kiran" "leif" "nita" "soren" "amit" "eira" "hari" "yuki" "raju" "lata")

# Generate tags derived from the base image tag.
# First tag preserves the original (e.g. "latest", "1.20"); subsequent tags
# increment as plausible versions when the tag looks numeric, else append index.
generate_tags() {
  local base_tag="$1" count="$2"
  local i
  printf '%s\n' "${base_tag}"
  if [[ "${base_tag}" =~ ^([0-9]+)\.([0-9]+)$ ]]; then
    # X.Y → X.Y.1, X.Y.2, ...
    local major="${BASH_REMATCH[1]}" minor="${BASH_REMATCH[2]}"
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${major}.${minor}.${i}"
    done
  elif [[ "${base_tag}" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
    # X.Y.Z → increment patch
    local major="${BASH_REMATCH[1]}" minor="${BASH_REMATCH[2]}" patch="${BASH_REMATCH[3]}"
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${major}.${minor}.$((patch + i))"
    done
  else
    # latest, slim, alpine, etc → append index
    for (( i=1; i<count; i++ )); do
      printf '%s\n' "${base_tag}-${i}"
    done
  fi
}

project_exists() {
  local name="$1"
  local code
  code="$(api_get -o /dev/null -w '%{http_code}' "${API}/projects/${name}")"
  [[ "${code}" == "200" ]]
}

create_project() {
  local name="$1" public_flag="$2"
  api_post -X POST "${API}/projects" \
    -d "{\"project_name\":\"${name}\",\"public\":${public_flag}}" \
    -o /dev/null -w '%{http_code}'
}

user_exists() {
  local username="$1"
  local body
  body="$(api_get "${API}/users/search?username=${username}")"
  [[ "$(echo "${body}" | jq -r 'length')" -gt 0 ]]
}

create_user() {
  local username="$1" password="$2" email="$3"
  api_post -X POST "${API}/users" \
    -d "{\"username\":\"${username}\",\"email\":\"${email}\",\"password\":\"${password}\",\"realname\":\"${username}\",\"comment\":\"dummy data user\"}" \
    -o /dev/null -w '%{http_code}'
}

# Push a dummy image with COUNT_TAGS tags into project/repo via docker.
push_dummy_image() {
  local project="$1" repo="$2" tag_count="$3" base_img="$4"
  local target="${MSR4_URL#*://}/${project}/${repo}"
  local base_tag="${base_img##*:}"

  # ensure we are logged in to the registry for docker push
  if ! docker login "${MSR4_URL#*://}" \
        --username "${MSR4_ADMIN_USERNAME}" \
        --password "${MSR4_ADMIN_PASSWORD}" >/dev/null 2>&1; then
    echo "  WARN: docker login to ${MSR4_URL#*://} failed; skipping image push for ${project}/${repo}" >&2
    return 0
  fi

  docker pull "${base_img}" >/dev/null 2>&1 || true

  local tag ref
  while IFS= read -r tag; do
    ref="${target}:${tag}"
    docker tag "${base_img}" "${ref}" >/dev/null 2>&1
    PUSHED_LOCAL_REFS+=("${ref}")
    if docker push "${ref}" >/dev/null 2>&1; then
      echo "    docker push ${ref} (from ${base_img})"
    else
      echo "    WARN: failed to push ${ref}" >&2
    fi
  done < <(generate_tags "${base_tag}" "${tag_count}")
}

# ---- main ------------------------------------------------------------------
login

# 1) users
echo
echo "== Creating ${USERS} dummy users =="
created_users=()
for (( u=1; u<=USERS; u++ )); do
  uname="${USER_NAMES[$(( (u-1) % ${#USER_NAMES[@]} ))]}"
  upass="Passw0rd-$((RANDOM % 100000))"
  mail="${uname}@example.com"
  if user_exists "${uname}"; then
    echo "  exists: ${uname}"
  else
    code="$(create_user "${uname}" "${upass}" "${mail}")"
    if [[ "${code}" == "201" || "${code}" == "200" ]]; then
      echo "  created: ${uname}"
    else
      echo "  WARN: create user ${uname} returned HTTP ${code}" >&2
    fi
  fi
  created_users+=("${uname}")
done

# 2) projects + repos + tags
echo
echo "== Creating ${COUNT_PROJECT} projects with repositories/tags =="
for (( p=1; p<=COUNT_PROJECT; p++ )); do
  pname="${PROJECT_NAMES[$(( (p-1) % ${#PROJECT_NAMES[@]} ))]}"
  if project_exists "${pname}"; then
    echo "  exists: ${pname}"
  else
    code="$(create_project "${pname}" false)"
    if [[ "${code}" == "201" || "${code}" == "200" ]]; then
      echo "  created project: ${pname}"
    else
      echo "  WARN: create project ${pname} returned HTTP ${code}; skipping" >&2
      continue
    fi
  fi

  total_repo=$(( COUNT_PRIVATE_REPO + COUNT_PUBLIC_REPO ))
  for (( r=1; r<=total_repo; r++ )); do
    if (( r <= COUNT_PUBLIC_REPO )); then
      visibility="public"
      # public repos go in a public sub-project-equivalent flag; Harbor projects
      # are the visibility unit, so create a public project for public repos.
      rproj="${pname}-public"
      if ! project_exists "${rproj}"; then
        create_project "${rproj}" true >/dev/null 2>&1 || true
      fi
      repo_target_project="${rproj}"
    else
      visibility="private"
      repo_target_project="${pname}"
    fi
    pick_base_image
    # Repo name = base image name (e.g. nginx, alpine, busybox)
    rname="${CURRENT_BASE_IMAGE%%:*}"
    echo "  [${visibility}] ${repo_target_project}/${rname} (${COUNT_TAGS_PER_PROJECT} tags) image=${CURRENT_BASE_IMAGE}"
    push_dummy_image "${repo_target_project}" "${rname}" "${COUNT_TAGS_PER_PROJECT}" "${CURRENT_BASE_IMAGE}"
  done
done

echo
echo "Done. Summary:"
echo "  users created : ${USERS}"
echo "  projects      : ${COUNT_PROJECT} private + ${COUNT_PUBLIC_REPO} public sub-projects"
echo "  repos/project : ${COUNT_PRIVATE_REPO} private + ${COUNT_PUBLIC_REPO} public"
echo "  tags/repo     : ${COUNT_TAGS_PER_PROJECT}"
